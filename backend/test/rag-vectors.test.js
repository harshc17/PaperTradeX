const { test } = require('node:test');
const assert = require('node:assert/strict');
const vectors = require('../src/services/RagVectors');
const { chunkDocument } = require('../src/services/RagRetrieval');
test('semantic retrieval finds concept matches, filters stale chunks and combines keyword ranks', async t => {
    const old = process.env.RAG_VECTOR_ENABLED, key = process.env.GEMINI_API_KEY;
    t.after(() => { for (const [k, v] of [['RAG_VECTOR_ENABLED', old], ['GEMINI_API_KEY', key]]) { if (v === undefined) delete process.env[k]; else process.env[k] = v; } });
    process.env.RAG_VECTOR_ENABLED = 'true'; process.env.GEMINI_API_KEY = 'test';
    const corpus = [{ id: 'a', title: 'Diversification', content: 'Spreading exposure across different assets can reduce concentration risk.' }, { id: 'b', title: 'Cash', content: 'Available balance is virtual cash.' }];
    const chunks = corpus.flatMap(chunkDocument);
    const rows = [{ chunkId: chunks[0].id, values: [1, 0] }, { chunkId: chunks[1].id, values: [0, 1] }, { chunkId: 'old-deleted-chunk', values: [1, 0] }];
    let query;
    const store = { find(filter) { query = filter; return { select() { return this; }, limit() { return this; }, lean: async () => rows }; } };
    const result = await vectors.search('avoid putting every egg in one basket', corpus, store, async () => [[1, 0]]);
    assert.equal(result.method, 'hybrid'); assert.equal(result.passages[0].documentId, 'a');
    assert.deepEqual(query.chunkId.$in.sort(), chunks.map(c => c.id).sort()); assert.equal(query.model, vectors.TAG);
    assert.ok(result.passages.every(c => c.id !== 'old-deleted-chunk'));
    const fallback = await vectors.search('cash', corpus, store, async () => { throw Error('offline'); });
    assert.equal(fallback.method, 'keyword'); assert.equal(fallback.passages[0].documentId, 'b');
    assert.equal(vectors.cosine([1, 0], [0, 1]), 0); assert.equal(vectors.cosine([0], [0]), -1);
    assert.equal(vectors.cosine([1], [1, 2]), -1);
    let writes = [];
    const indexStore = { find: () => ({ select() { return this; }, lean: async () => [] }), bulkWrite: async ops => { writes = ops; } };
    const indexed = await vectors.index(corpus, indexStore, async texts => texts.map(() => [1, 0]));
    assert.equal(indexed.remaining, 0); assert.equal(writes.length, chunks.length);
    assert.ok(writes.every(w => !JSON.stringify(w).includes('balance is virtual')));
});
test('embedding API uses Gemini headers, bounded dimensions and task prefixes; malformed vectors fail', async t => {
    const oldFlag = process.env.RAG_VECTOR_ENABLED, oldKey = process.env.GEMINI_API_KEY, originalFetch = global.fetch;
    t.after(() => { global.fetch = originalFetch; for (const [k, v] of [['RAG_VECTOR_ENABLED', oldFlag], ['GEMINI_API_KEY', oldKey]]) { if (v === undefined) delete process.env[k]; else process.env[k] = v; } });
    process.env.RAG_VECTOR_ENABLED = 'true'; process.env.GEMINI_API_KEY = 'test-only';
    let request, target, headers, invalid = false;
    global.fetch = async (url, init) => { target = url; headers = init.headers; request = JSON.parse(init.body); return { ok: true, json: async () => ({ embeddings: [{ values: invalid ? [NaN] : Array(768).fill(.1) }] }) }; };
    assert.equal((await vectors.embed(['diversification'], true))[0].length, 768);
    assert.ok(target.endsWith('gemini-embedding-2:batchEmbedContents')); assert.ok(!target.includes('test-only'));
    assert.equal(headers['x-goog-api-key'], 'test-only'); assert.equal(request.requests[0].outputDimensionality, 768);
    assert.match(request.requests[0].content.parts[0].text, /^task: search result/);
    invalid = true; await assert.rejects(vectors.embed(['x']), /Invalid embeddings/);
    assert.notEqual(chunkDocument({ id: 'x', title: 'Before', content: 'text' })[0].id, chunkDocument({ id: 'x', title: 'After', content: 'text' })[0].id);
});
