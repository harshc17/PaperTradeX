'use client';
import { API_URL } from '@/lib/config';
import { useState } from 'react';
import { CheckCircle2, AlertCircle, Lightbulb, RefreshCw } from 'lucide-react';
import { usePortfolio } from '@/context/PortfolioContext';

export default function AIPortfolioAnalyst() {
    const { holdings } = usePortfolio();
    const [analysis, setAnalysis] = useState<any>(null);
    const [loading, setLoading] = useState(false);
    const [error, setError] = useState('');

    const generateAnalysis = async () => {
        if (holdings.length === 0) { setError("Add a holding before requesting a portfolio review."); return; }
        setLoading(true); setError('');
        try {
            const token = localStorage.getItem('ptx_token') || localStorage.getItem('token') || '';
            const res = await fetch(`${API_URL}/api/ai/portfolio`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json', 'Authorization': `Bearer ${token}` },
                body: JSON.stringify({ holdings }),
            });
            if (res.status === 404) throw new Error('Portfolio analysis is currently unavailable.');
            if (!res.ok) { const e = await res.json().catch(() => ({})); throw new Error(e.error || 'Failed to fetch AI analysis'); }
            setAnalysis(await res.json());
        } catch (err: any) {
            setError(err.message || 'Something went wrong.');
        } finally { setLoading(false); }
    };

    return (
        <div className="rounded-2xl border p-6 relative overflow-hidden"
            style={{ background: 'var(--surface)', borderColor: 'var(--surface-border)' }}>

            <div className="relative z-10">
                <div className="flex items-center justify-between mb-5">
                    <h3 className="text-base font-medium text-ink-heading flex items-center gap-2 font-heading">

                        Portfolio review
                    </h3>
                    {analysis && (
                        <button onClick={generateAnalysis} disabled={loading} className="text-ink-faint hover:text-ink-muted transition-colors">
                            <RefreshCw className={`w-4 h-4 ${loading ? 'animate-spin' : ''}`} />
                        </button>
                    )}
                </div>

                {!analysis && !loading && (
                    <div className="text-left">
                        <p className="text-sm text-ink-muted mb-4 leading-relaxed">
                            Review your virtual holdings for concentration, strengths and risks. Analysis is generated by AI.
                        </p>
                        <button onClick={generateAnalysis}
                            className="w-full py-2.5 text-[var(--primary-ink)] text-sm font-medium rounded-xl transition-colors"
                            style={{ background: 'var(--surface-2)', color: 'var(--text-main)' }}>
                            Review portfolio
                        </button>
                        {error && <p className="text-down text-xs mt-3">{error}</p>}
                    </div>
                )}

                {loading && (
                    <div className="text-center py-6">
                        <div className="w-10 h-10 border-2 border-primary/20 border-t-primary rounded-full animate-spin mx-auto mb-4" />
                        <p className="text-sm text-ink-faint animate-pulse">AI is analyzing your holdings...</p>
                    </div>
                )}

                {analysis && !loading && (
                    <div className="space-y-4">
                        <div className="bg-white/5 border border-white/8 rounded-xl p-4">
                            <p className="text-sm text-[var(--text-main)] leading-relaxed">{analysis.summary}</p>
                        </div>
                        {[
                            { key: 'strengths', label: 'Strengths', icon: <CheckCircle2 className="w-3.5 h-3.5 text-up" />, dot: 'bg-up/50' },
                            { key: 'weaknesses', label: 'Areas of Risk', icon: <AlertCircle className="w-3.5 h-3.5 text-ink-muted" />, dot: 'bg-[#f5a623]/50' },
                            { key: 'recommendations', label: 'Recommendations', icon: <Lightbulb className="w-3.5 h-3.5 text-ink-muted" />, dot: 'bg-[#fbbf24]/50' },
                        ].map(({ key, label, icon, dot }) => analysis[key]?.length > 0 && (
                            <div key={key}>
                                <h4 className="text-xs font-medium text-ink-faint mb-2 flex items-center gap-1.5">{icon}{label}</h4>
                                <ul className="space-y-1.5">
                                    {analysis[key].map((item: string, i: number) => (
                                        <li key={i} className={`text-sm text-ink-muted pl-5 relative before:content-[''] before:absolute before:left-1.5 before:top-2 before:w-1.5 before:h-1.5 before:rounded-full before:${dot}`}>{item}</li>
                                    ))}
                                </ul>
                            </div>
                        ))}
                    </div>
                )}
            </div>
        </div>
    );
}
